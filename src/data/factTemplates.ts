// ─── HELPER EXPORTS ──────────────────────────────────────────────────────────
export const FACT_TEMPLATE_MAP = Object.fromEntries(
  FACT_TEMPLATES.map((t) => [t.fact_key, t])
) as Record<string, FactTemplate>;

export const FACT_KEYS_BY_CATEGORY = FACT_TEMPLATES.reduce<
  Record<FactCategory, string[]>
>((acc, t) => {
  if (!acc[t.category]) acc[t.category] = [];
  acc[t.category].push(t.fact_key);
  return acc;
}, {} as Record<FactCategory, string[]>);

export const FACT_KEYS_BY_TIER = FACT_TEMPLATES.reduce<
  Record<PriorityTier, string[]>
>((acc, t) => {
  if (!acc[t.tier]) acc[t.tier] = [];
  acc[t.tier].push(t.fact_key);
  return acc;
}, {} as Record<PriorityTier, string[]>);

/**
 * Verilen konsept tipine göre ilgili fact şablonlarını döner.
 */
export function getTemplatesForConcept(concept: ConceptType): FactTemplate[] {
  return FACT_TEMPLATES.filter(
    (t) =>
      t.applies_to_concepts === 'all' ||
      t.applies_to_concepts.includes(concept)
  );
}
